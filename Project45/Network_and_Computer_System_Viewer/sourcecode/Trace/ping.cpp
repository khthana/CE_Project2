//Internal class which is used to ensure that the ICMP
//function pointers are available 
class _CPING_ICMP
{
public:
//Constructors / Destructors
  _CPING_ICMP();
	~_CPING_ICMP();

protected:
//Member variables
  HINSTANCE         m_hIcmp;         //HINSTANCE of ICMP.DLL
  CPing::LPICMPCREATEFILE  m_pIcmpCreateFile;
  CPing::LPICMPSENDECHO    m_pIcmpSendEcho;
  CPing::LPICMPCLOSEHANDLE m_pIcmpCloseHandle;

	friend class CPing;
};

_CPING_ICMP::_CPING_ICMP()
{
	//Load up the ICMP library
	m_hIcmp = LoadLibrary(_T("ICMP.DLL"));
	if (m_hIcmp)
  {
	  //Retrieve pointers to the functions in the ICMP dll
	  m_pIcmpCreateFile = (CPing::LPICMPCREATEFILE) GetProcAddress(m_hIcmp,"IcmpCreateFile");
	  m_pIcmpSendEcho = (CPing::LPICMPSENDECHO) GetProcAddress(m_hIcmp,"IcmpSendEcho" );
	  m_pIcmpCloseHandle = (CPing::LPICMPCLOSEHANDLE) GetProcAddress(m_hIcmp,"IcmpCloseHandle");

	  if (m_pIcmpCreateFile == NULL || m_pIcmpSendEcho == NULL ||	m_pIcmpCloseHandle == NULL)
    {
		  TRACE(_T("_CPING_ICMP::_CPING_ICMP, Could not find the required functions in the ICMP DLL\n"));

      FreeLibrary(m_hIcmp);
      m_hIcmp = NULL;
    }
  }
  else
		TRACE(_T("_CPING_ICMP::_CPING_ICMP, Could not load up the ICMP DLL\n"));
}

_CPING_ICMP::~_CPING_ICMP()
{
	if (m_hIcmp)
	{
		FreeLibrary(m_hIcmp);
		m_hIcmp = NULL;
  }
}

