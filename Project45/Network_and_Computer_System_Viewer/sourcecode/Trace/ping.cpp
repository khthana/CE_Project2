BOOL CPing::PingUsingICMP(LPCTSTR pszHostName, CPingReply& pr, UCHAR nTTL, DWORD dwTimeout, int nDataSize, UCHAR nTOS, BOOL bDontFragment) const
{
	//For correct operation of the T2A macro, see TN059
	USES_CONVERSION;

	//Make sure ICMP dll is available
	if (_cpingData.m_hIcmp == NULL)
  {
    TRACE(_T("CPing::PingUsingICMP, ICMP dll is not available\n"));
    SetLastError(ERROR_FILE_NOT_FOUND);
	  return FALSE;
  }

	LPSTR lpszAscii = T2A((LPTSTR) pszHostName);
	//Convert from dotted notation if required
	unsigned long	addr = inet_addr(lpszAscii);
	if (addr == INADDR_NONE)
	{
		//Not a dotted address, then do a lookup of the name
		hostent* hp = gethostbyname(lpszAscii);
		if (hp)
			memcpy(&addr, hp->h_addr, hp->h_length);
		else
		{
			TRACE(_T("CPing::PingUsingICMP, Could not resolve the host name %s\n"), pszHostName);
			return FALSE;
		}
	}

  //Create the ICMP handle
  ASSERT(_cpingData.m_pIcmpCreateFile);
	HANDLE hIP = _cpingData.m_pIcmpCreateFile();
	if (hIP == INVALID_HANDLE_VALUE)
	{
		TRACE(_T("CPing::PingUsingICMP, Could not get a valid ICMP handle\n"));
		return FALSE;
	}

  //Set up the option info structure
	IP_OPTION_INFORMATION OptionInfo;
	ZeroMemory(&OptionInfo, sizeof(IP_OPTION_INFORMATION));
	OptionInfo.Ttl = nTTL;
  OptionInfo.Tos = nTOS;
  if (bDontFragment)
    OptionInfo.Flags = IP_FLAG_DF;

  //Set up the data which will be sent
  unsigned char* pBuf = new unsigned char[nDataSize];
  memset(pBuf, 'E', nDataSize);

	//Do the actual Ping
  int nReplySize = sizeof(ICMP_ECHO_REPLY) + nDataSize;
  unsigned char* pReply = new unsigned char[nReplySize];
	ICMP_ECHO_REPLY* pEchoReply = (ICMP_ECHO_REPLY*) pReply;
  ASSERT(_cpingData.m_pIcmpSendEcho);
  DWORD nRecvPackets = _cpingData.m_pIcmpSendEcho(hIP, addr, pBuf, (UCHAR)nDataSize, &OptionInfo, pReply, nReplySize, dwTimeout);

  //Check we got the packet back
  BOOL bSuccess = (nRecvPackets == 1);

  //Check the data we got back is what was sent
  if (bSuccess)
  {
    char* pReplyData = (char*) pEchoReply->Data;
    for (int i=0; i<pEchoReply->DataSize && bSuccess; i++)
      bSuccess = (pReplyData[i] == 'E');

    if (!bSuccess)
    {
      TRACE(_T("CPing::PingUsingICMP, Could not get a valid ICMP response\n"));
      SetLastError(ERROR_UNEXP_NET_ERR);
    }
  }

  //Close the ICMP handle
  ASSERT(_cpingData.m_pIcmpCloseHandle);
	_cpingData.m_pIcmpCloseHandle(hIP);

	if (bSuccess)
	{
    //Ping was successful, copy over the pertinent info
    //into the return structure
		pr.Address.S_un.S_addr = pEchoReply->Address;
	  pr.RTT = pEchoReply->RoundTripTime;
    pr.EchoReplyStatus = pEchoReply->Status;
	}

  //Free up the memory we allocated
  delete [] pBuf;
  delete [] pReply;

  //return the status
	return bSuccess; 
}
