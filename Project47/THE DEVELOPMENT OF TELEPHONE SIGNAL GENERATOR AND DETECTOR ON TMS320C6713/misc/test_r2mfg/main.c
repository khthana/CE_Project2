MdInt test[80];
Int outfio[80];
MdInt genc,i;	// kontrol var.

    R2MFG_Handle  handle;
    IR2MFG_Fxns   fxns;
    R2MFG_Params  params;


void main()
{
	
	ALGRF_setup(INTERNALHEAP,EXTERNALHEAP);
	
    fxns = R2MFG_KASATKA_IR2MFG;
    
    //params = R2MFG_PARAMS;  
    params.ptr2konst = &r2mfg_Konst;  
    params.array_elem = 80;
    params.percent_pow = 55;
    params.target_array = test;
    params.size = sizeof(params);	

    R2MFG_init();
    if((handle = R2MFG_create(&fxns, &params)) != NULL){
        
	    genc = 0;
	    i=10;
    }
    else{
	   
    	R2MFG_exit();
    }
    return;
}

