void ps()
{
	MdInt ret,j;

    if (genc < 0x20)
    {
    	if (i<10)	
    	{
    		i++;
    	}else
    	{
    		genc++;
    		i=0;
    		R2MFG_setDigit(handle,genc);
    	}

    	R2MFG_setState(handle,1);
    	
    		STS_set(&STS_CLK, CLK_gethtime());
    	ret = R2MFG_apply(handle);
    		STS_delta(&STS_CLK, CLK_gethtime());
     	
     	if ( ret != 0)
     	{
		    for (j = 0; j < 80; j++) 
		    {
				outfio[j] = test[j];		
	    	}//for 
	    	j=0;	//for prob-point sync. purpose, no other meaning        		
     	}//if         				         				         	      	     	      	       	             	
    }//while
        
return;
}

