MdInt test[80];

#define GQ_ELEM 20
Char gQ[GQ_ELEM];

Int outfio[80];

DTMFG_Handle  handle;
IDTMFG_Fxns   fxns;
DTMFG_Params  params;    

void main()
{
	ALGRF_setup(INTERNALHEAP,EXTERNALHEAP);
	
    fxns = DTMFG_KASATKA_IDTMFG;
    
    //params = DTMFG_PARAMS;
    params.size = sizeof(IDTMFG_Params);
    params.pause_len = 800;
    params.signal_len = 800;
    params.target_array = test;
    params.array_elem = 80;
    params.genQ = gQ;
    params.genQ_elem = GQ_ELEM;    
    params.ptr2konst = &dtmfg_Konst;      
	

    DTMFG_init();	
        
    if((handle = DTMFG_create(&fxns, &params)) != NULL) 
    {

        DTMFG_enqueue(handle,1);
        DTMFG_enqueue(handle,2);
        DTMFG_enqueue(handle,3);
        DTMFG_enqueue(handle,4);
        DTMFG_enqueue(handle,5);
        DTMFG_enqueue(handle,6);
        DTMFG_enqueue(handle,7);
        DTMFG_enqueue(handle,8);
        DTMFG_enqueue(handle,9);
        DTMFG_enqueue(handle,10);	// *
        DTMFG_enqueue(handle,0);   	     
        DTMFG_enqueue(handle,11);	// #
        
        DTMFG_enqueue(handle,12);	// A
        DTMFG_enqueue(handle,13);	// B
        DTMFG_enqueue(handle,14);	// C
        DTMFG_enqueue(handle,15);	// D    
        // ---
 		
        // ---                                                                                            
        DTMFG_setEnable(handle,1,0);                                                                                     
        
    }else
    {  
    	DTMFG_exit();
    }
 
	return;
}


