void ps()
{
	MdInt gr;
	Int i,j;
	//LOG_printf(&trace,"Hello!!!");	

	STS_set(&STS_CLK, CLK_gethtime());
	gr = DTMFG_apply(handle);	 				
	STS_delta(&STS_CLK, CLK_gethtime());

	if (gr == 1)
	{
	    for (i = 0, j=0; i < 80; i++, j+=2) 
	    {
			outfio[i] = test[i];		
    	}
		gr = 1;	// prob-point only, there's no any meaning	    	
    }
	return;
}

