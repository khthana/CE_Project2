    private void QueryButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_QueryButtonActionPerformed
        // Add your handling code here:
        
        VillageContainer vc=null;
        RoadContainer rc=null;
        String cond;
//Vector VillageAll,VillageCond,RoadAll,RoadCond;
        String ad=Integer.toString(MonthComboBox.getSelectedIndex()+1)+"/"+
        Integer.toString(DateComboBox.getSelectedIndex()+1)+"/"+year[YearComboBox.getSelectedIndex()];
        Date AtDate=new Date(ad);
//MapFrame         
        MapFrame mf=(MapFrame)MVector.elementAt(0);
        mf.addMapDetail(ad,VQTextField.getText(),RQTextField.getText());
        mf.DrawAreaPanel.VillageAll.clear();
        mf.DrawAreaPanel.RoadAll.clear();
        mf.DrawAreaPanel.VillageCond.clear();
        mf.DrawAreaPanel.RoadCond.clear();
//        mf.DrawAreaPanel.VillageAttribute.clear();
//        mf.DrawAreaPanel.RoadAttribute.clear();
        mf.clearTable();
//UpdateFrame
        UpdateFrame uf=(UpdateFrame)UVector.elementAt(0);
        uf.VillageCond.clear();
        uf.RoadCond.clear();
        uf.clearFrame();
        int i=0;
        if (VillageRadioButton.isSelected() || AllRadioButton.isSelected())
        {
            //Vector GetAllVillage(Date AtDate)
            Vector tmpvec1=new Vector();
            VContain.id=0;
            tmpvec1=VContain.GetAllVillage(AtDate);
            //if (tmpvec1.size()>0)
            if (VContain.id>0)
            {
               for(i=0;i<tmpvec1.size();i++)
               {
                vc=(VillageContainer)tmpvec1.elementAt(0);		
                vc.Print();           
               }
                System.out.println("VAll "+Integer.toString(tmpvec1.size()));
                mf.DrawAreaPanel.VillageAll=tmpvec1;   
                mf.DrawAreaPanel.VillageAttribute=tmpvec1;
                System.out.println("getAllVillage");
            }
         }

        if(RoadRadioButton.isSelected() || AllRadioButton.isSelected())
        {
            RContain.id=0;
            Vector tmpvec2=new Vector() ;
            tmpvec2=RContain.GetAllRoad(AtDate);
            //if (tmpvec2.size()>0)
            if(RContain.id>0)
            {
                rc=(RoadContainer)tmpvec2.elementAt(0);		
                rc.Print();                
                mf.DrawAreaPanel.RoadAll=tmpvec2;   
                mf.DrawAreaPanel.RoadAttribute=tmpvec2;
                System.out.println("getAllRoad");
            }
        }
        cond=VQTextField.getText();
        if ((cond.length())>0)
        {
            VContain.id=0;
            //SearchVillage(String SearchExpr,Date AtDate)
            Vector tmpvec3=new Vector();
            tmpvec3=VContain.SearchVillage(cond,AtDate);
            //if (tmpvec3!=null)
            //if (tmpvec3.size()>0)
            if (VContain.id>0)
            {
                vc=(VillageContainer)tmpvec3.elementAt(0);		
                vc.Print();                
                mf.DrawAreaPanel.VillageCond=tmpvec3;   
//                mf.DrawAreaPanel.VillageAttribute.clear();
                mf.DrawAreaPanel.VillageAttribute=tmpvec3;
                uf.VillageCond=tmpvec3;
                //uf.Test.setText("Hello");
                uf.addVillageName();
            }
        }
        cond=RQTextField.getText();
        if ((cond.length())>0)
        {
            RContain.id=0;
            //SearchRoad(String SearchExpr,Date AtDate)
            Vector tmpvec4=new Vector();
            tmpvec4=RContain.SearchRoad(cond,AtDate);
            //if (tmpvec4.size()>0)
            if(RContain.id>0)
            {
                rc=(RoadContainer)tmpvec4.elementAt(0);		
                rc.Print();                
                mf.DrawAreaPanel.RoadCond=tmpvec4;   
//                mf.DrawAreaPanel.RoadAttribute.clear();
                mf.DrawAreaPanel.RoadAttribute=tmpvec4;
                uf.RoadCond=tmpvec4;
                uf.addRoadName();
            }
        }
//******************************************************************        
        String val="true";
        int pcount=0;
        if (mf.DrawAreaPanel.VillageAttribute.size()>0)
        {
            pcount=mf.DrawAreaPanel.VillageAttribute.size();
            System.out.println("mf.DrawAreaPanel.VillageAttribute.size() : "+ pcount);
            mf.resetAPoint(pcount,mf.DrawAreaPanel.VAShow);
            mf.AddVillageAttribute();
        }
        if (mf.DrawAreaPanel.RoadAttribute.size()>0)
        {
            pcount=mf.DrawAreaPanel.RoadAttribute.size();
            mf.resetAPoint(pcount,mf.DrawAreaPanel.RAShow);
            mf.AddRoadAttribute();
        }
//******************************************************************
        mf.DrawAreaPanel.repaint();
        mf.show();
        uf.show();
    }//GEN-LAST:event_QueryButtonActionPerformed

