    private void FieldListMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_FieldListMouseClicked
        // Add your handling code here:
        
        if (!(FieldList.isSelectionEmpty()))
        {
        String str=FieldList.getSelectedValue()+" ";
        JTextField tempComp;
        if (str.indexOf("Village")>=0)
            tempComp = VQTextField;
        else
            tempComp = RQTextField;
        String qtext=tempComp.getText();
        if ((qtext.length()-1)!=qtext.lastIndexOf(' '))
            qtext=qtext+" ";
        if (qtext.equals(" ")) 
            qtext=str;
        else
            qtext=qtext+str;
        tempComp.setText(qtext);
        focusVector=tempComp.getName();        
        
        }
    }//GEN-LAST:event_FieldListMouseClicked

