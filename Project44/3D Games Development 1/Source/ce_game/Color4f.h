class CColor4f  
{
public:
	//---members function-----------------------------------------------------------------
	FLOAT r, g, b, a;

	//---constructors & destructor--------------------------------------------------------
	virtual ~CColor4f();

	CColor4f()										 { r=0.0f; g=0.0f; b=0.0f; a=1.0f; }
	CColor4f(FLOAT R, FLOAT G, FLOAT B, FLOAT A=1.0f){ r=R; g=G; b=B; a=A; }
	CColor4f(DWORD argb)
	{	
		r=((argb&0x00ff0000)>>16)/255.f; 
		g=((argb&0x0000ff00)>> 8)/255.f; 
		b=((argb&0x000000ff)    )/255.f; 
		a=((argb&0xff000000)>>24)/255.f;
	}

	//---operators------------------------------------------------------------------------
	CColor4f operator= (const CColor4f&	 c)	{ r=c.r; g=c.g; b=c.b; a=c.a; return *this; }
//	CColor4f operator= (const D3DXCOLOR& c)	{ r=c.r; g=c.g; b=c.b; a=c.a; return *this; }

	//---members variable-----------------------------------------------------------------
	GLfloat* GetGLfloat(GLfloat* p) { *p=r; *(p+1)=g; *(p+2)=b; *(p+3)=a; return p; }
//	GLfloat* GetGLfloat(GLfloat* p) { *p[0]=r; *p[1]=g; *p[2]=b; *p[3]=a; return p; }
};



#endif // __COLOR4F_H__
