Entity InstMem is
generic (inst_width			: integer := 100;
		 bit_addr			: integer := 16;
		 size				: integer := 16);

port (oe	: in std_logic;
	  cs	: in std_logic;
	  addr	: in unsigned(bit_addr-1 downto 0);
	  data	: inout unsigned(inst_width-1 downto 0));
End InstMem;

Architecture behavior of InstMem is

	type memory_array is array(0 to size - 1) of unsigned(inst_width-1 downto 0);
	signal mem		: memory_array;
	signal address_n	: integer;

	Function to_integer(a : in unsigned(bit_addr-1 downto 0)) return integer is
		variable sum	: integer := 0;
		variable tmp	: integer;
		variable tmp2	: integer;
	begin
		for i in bit_addr-1 downto 0 loop
			tmp := 2**i;
			if (a(i) = '0') then tmp2 := 0;
			elsif (a(i) = '1') then tmp2 := 1; end if;
			sum := sum + (tmp * tmp2);
		end loop;
		return sum;
	end to_integer;

