    private String[] getip(){
        String[] ip = new String[3]; 
        try
        {
            InetAddress inetHost = InetAddress.getLocalHost();
            InetAddress[] inet = InetAddress.getAllByName(inetHost.getHostName());
            for (int x=0; x<inet.length; x++)
                ip[x]=inet[x].getHostAddress();
                //System.out.println("IP " + (x+1) +": " + inet[x].getHostAddress());
        }
            catch(UnknownHostException e){
                System.out.print("error host");
            }
            return ip;
    }
    
